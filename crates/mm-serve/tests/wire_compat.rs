//! Wire compatibility: golden JSON fixtures round-trip, and `export_types`
//! regenerates the TypeScript mirror (plan `01` §7, `10` §2).
//!
//! Fixtures live in `frontend/src/lib/wire/fixtures/` so the SPA tests and this
//! crate assert the same bytes. Regenerate the mirror with:
//!
//! ```text
//! cargo test -p mm-serve export_types -- --ignored
//! ```

use std::path::{Path, PathBuf};

use mm_serve::dto::chat::ChatFrame;
use mm_serve::dto::focus::FocusDoc;
use mm_serve::dto::{ApiError, HealthEnvelope};
use serde::de::DeserializeOwned;
use serde::Serialize;
use ts_rs::TS;

fn wire_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../frontend/src/lib/wire")
}

fn fixture(name: &str) -> PathBuf {
    wire_dir().join("fixtures").join(name)
}

fn assert_canonical<T>(name: &str)
where
    T: Serialize + DeserializeOwned + PartialEq + std::fmt::Debug,
{
    let path = fixture(name);
    let raw =
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let trimmed = raw.trim_end_matches('\n');
    let value: T = serde_json::from_str(trimmed)
        .unwrap_or_else(|e| panic!("parse {}: {e}\n{trimmed}", path.display()));
    let encoded = serde_json::to_string(&value).unwrap();
    assert_eq!(
        encoded,
        trimmed,
        "fixture {} is not canonical serde_json",
        path.display()
    );
    let again: T = serde_json::from_str(&encoded).unwrap();
    assert_eq!(value, again, "round trip {}", path.display());
}

#[test]
fn health_fixture_round_trips() {
    assert_canonical::<HealthEnvelope>("health.json");
}

#[test]
fn api_error_fixture_round_trips() {
    assert_canonical::<ApiError>("api_error.json");
}

#[test]
fn chat_frames_fixture_round_trips() {
    assert_canonical::<Vec<ChatFrame>>("chat_frames.json");
}

#[test]
fn focus_doc_fixture_round_trips() {
    assert_canonical::<FocusDoc>("focus_doc.json");
}

/// Writes `frontend/src/lib/wire/{index,chat,focus}.ts` from the DTO derives.
///
/// Ignored so a normal `cargo test` does not touch the tree; CI runs it and
/// fails if the committed mirror drifted.
#[test]
#[ignore = "writes frontend/src/lib/wire; run: cargo test -p mm-serve export_types -- --ignored"]
fn export_types() {
    let cfg = ts_rs::Config::from_env().with_large_int("number");
    let dir = wire_dir();
    std::fs::create_dir_all(dir.join("fixtures")).unwrap();
    write_module(
        &dir.join("index.ts"),
        "crates/mm-serve/src/dto/mod.rs",
        &[
            <mm_serve::dto::ApiErrorCode as TS>::decl(&cfg),
            <mm_serve::dto::ApiError as TS>::decl(&cfg),
            <mm_serve::dto::ServiceState as TS>::decl(&cfg),
            <mm_serve::dto::ServiceStatus as TS>::decl(&cfg),
            <mm_serve::dto::KernelStatus as TS>::decl(&cfg),
            <mm_serve::dto::EventHead as TS>::decl(&cfg),
            <mm_serve::dto::HealthEnvelope as TS>::decl(&cfg),
        ],
        "export const WIRE_VERSION = 1 as const;\n",
    );
    write_module(
        &dir.join("chat.ts"),
        "crates/mm-serve/src/dto/chat.rs",
        &[
            <mm_serve::dto::chat::Phase as TS>::decl(&cfg),
            <mm_serve::dto::chat::ChatRunState as TS>::decl(&cfg),
            <ChatFrame as TS>::decl(&cfg),
        ],
        "",
    );
    write_module(
        &dir.join("focus.ts"),
        "crates/mm-serve/src/dto/focus.rs",
        &[
            <mm_serve::dto::focus::DocKind as TS>::decl(&cfg),
            <mm_serve::dto::focus::DocStatus as TS>::decl(&cfg),
            <mm_serve::dto::focus::DocCapability as TS>::decl(&cfg),
            <mm_serve::dto::focus::EpistemicStatus as TS>::decl(&cfg),
            <mm_serve::dto::focus::DocSourceKind as TS>::decl(&cfg),
            <mm_serve::dto::focus::DocSource as TS>::decl(&cfg),
            <FocusDoc as TS>::decl(&cfg),
        ],
        "",
    );
}

fn write_module(path: &Path, source: &str, decls: &[String], trailer: &str) {
    let mut out = String::new();
    out.push_str("// @generated by `cargo test -p mm-serve export_types -- --ignored`.\n");
    out.push_str("// Do not edit by hand.\n");
    out.push_str("// Source of truth: ");
    out.push_str(source);
    out.push_str(".\n\n");
    for decl in decls {
        let trimmed = decl.trim();
        if trimmed.is_empty() {
            continue;
        }
        // `TS::decl` omits the export keyword; the mirror is a public module.
        if !trimmed.starts_with("export ") {
            out.push_str("export ");
        }
        out.push_str(trimmed);
        if !trimmed.ends_with('\n') {
            out.push('\n');
        }
        out.push('\n');
    }
    out.push_str(trailer);
    if !out.ends_with('\n') {
        out.push('\n');
    }
    std::fs::write(path, out).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

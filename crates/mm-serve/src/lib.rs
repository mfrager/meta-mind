//! `mm-serve` — the MetaMind Web Console server.
//!
//! The console is a second operator surface over the same kernel the CLI drives
//! (plan: [`design/planning/ui/`](../../../design/planning/ui/INDEX.md)). It is
//! a single local process that owns the data directory while it runs
//! (`data/console.lock`), calls the same library entry points `mm-cli` calls,
//! and exposes typed JSON over HTTP plus resumable SSE streams.
//!
//! Milestone M0 (plan `10` §2) delivers the skeleton this module set shapes:
//! kernel boot with a doctor-style preflight, `GET /api/health`, and the SSE
//! frame codec every later stream (chat, focus, logs) is written with. The wire
//! types in [`dto`] are the single source of truth for the TypeScript mirror in
//! `frontend/src/lib/wire/`, regenerated by `cargo test -p mm-serve export_types -- --ignored`.

